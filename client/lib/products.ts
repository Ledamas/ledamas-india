export function getProductsByCollection(collectionSlug: string): Product[] {
  if (collectionSlug === 'all') {
    return PRODUCTS;
  }
  switch (collectionSlug) {
    case 'kunafa-chocolate':
      return PRODUCTS.filter((p) => p.slug.includes('kunafa'));
    case 'dubai-chocolate':
      return PRODUCTS.filter((p) => p.slug.includes('kunafa') || p.categorySlug === 'kunafa-chocolate');
    case 'dark-chocolate':
      return PRODUCTS.filter((p) => p.categorySlug === 'dark-chocolate' || p.cacaoPercentage || p.slug.includes('dark'));
    case 'milk-chocolate':
      return PRODUCTS.filter((p) => p.categorySlug === 'milk-chocolate' || p.name.toLowerCase().includes('milk') || p.name.toLowerCase().includes('white'));
    case 'mini-chocolate-bars':
      return PRODUCTS.filter((p) => p.weight === '35gm' || p.slug.includes('mini'));
    case 'pistachio-chocolate':
      return PRODUCTS.filter((p) => p.slug.includes('pistachio') || p.name.toLowerCase().includes('pistachio'));
    default:
      return PRODUCTS.filter((p) => p.categorySlug === collectionSlug);
  }
}

export function getRelatedProducts(currentProduct: Product, limit: number = 3): Product[] {
  return PRODUCTS.filter(
    (p) => p.id !== currentProduct.id && (p.categorySlug === currentProduct.categorySlug || p.slug.includes('kunafa'))
  ).slice(0, limit);
}

